-- Aplica una lista de fertilizantes a una siembra/parcela en una sola llamada
CREATE OR REPLACE PROCEDURE sp_aplicar_fertilizantes (
  p_lista      IN t_lista_usos,
  p_parcela_id IN NUMBER,
  p_siembra_id IN NUMBER DEFAULT NULL,
  p_usuario_id IN NUMBER,
  p_fecha      IN DATE DEFAULT SYSDATE
) AS
BEGIN
  IF p_lista IS NULL OR p_lista.COUNT = 0 THEN
    RAISE_APPLICATION_ERROR(-20002, 'La lista de fertilizantes no puede estar vacía.');
  END IF;

  FOR i IN 1 .. p_lista.COUNT LOOP
    IF p_lista(i).cantidad_kg <= 0 THEN
      RAISE_APPLICATION_ERROR(-20003,
        'La cantidad debe ser mayor a 0 (ítem ' || i || ').');
    END IF;

    INSERT INTO usos_fertilizante
      (fertilizante_id, siembra_id, parcela_id, cantidad_kg, fecha_uso, usuario_id)
    VALUES
      (p_lista(i).fertilizante_id, p_siembra_id, p_parcela_id,
       p_lista(i).cantidad_kg, p_fecha, p_usuario_id);
  END LOOP;

  COMMIT;
END sp_aplicar_fertilizantes;
/

-- Registra múltiples jornadas laborales para un trabajador en un lote
CREATE OR REPLACE PROCEDURE sp_registrar_jornadas (
  p_trabajador_id IN NUMBER,
  p_usuario_id    IN NUMBER,
  p_lista         IN t_lista_horas
) AS
BEGIN
  IF p_lista IS NULL OR p_lista.COUNT = 0 THEN
    RAISE_APPLICATION_ERROR(-20004, 'La lista de jornadas no puede estar vacía.');
  END IF;

  FOR i IN 1 .. p_lista.COUNT LOOP
    IF p_lista(i).horas <= 0 OR p_lista(i).horas > 24 THEN
      RAISE_APPLICATION_ERROR(-20005,
        'Horas fuera de rango en jornada ' || i || ' (debe ser entre 0 y 24).');
    END IF;

    INSERT INTO horas_laboradas
      (trabajador_id, fecha, horas, descripcion, usuario_id)
    VALUES
      (p_trabajador_id, p_lista(i).fecha, p_lista(i).horas,
       p_lista(i).descripcion, p_usuario_id);
  END LOOP;

  COMMIT;
END sp_registrar_jornadas;
/

-- Devuelve total de horas de un trabajador en un rango de fechas
CREATE OR REPLACE FUNCTION fn_horas_trabajador (
  p_trabajador_id IN NUMBER,
  p_desde         IN DATE DEFAULT TRUNC(SYSDATE, 'MM'),
  p_hasta         IN DATE DEFAULT SYSDATE
) RETURN NUMBER AS
  v_total NUMBER := 0;
BEGIN
  SELECT NVL(SUM(horas), 0)
    INTO v_total
    FROM horas_laboradas
   WHERE trabajador_id = p_trabajador_id
     AND fecha BETWEEN p_desde AND p_hasta;
  RETURN v_total;
END fn_horas_trabajador;
/

