-- ─── SECCIÓN 3: Usuarios (multi-tenant root) ──────────────────────────────────

CREATE TABLE usuarios (
  id            NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre        VARCHAR2(120) NOT NULL,
  email         VARCHAR2(160) NOT NULL,
  password_hash VARCHAR2(255) NOT NULL,
  rol_id        NUMBER(10),
  estado_id     NUMBER(10),
  created_at    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at    TIMESTAMP,
  CONSTRAINT uq_usuarios_email  UNIQUE (email),
  CONSTRAINT fk_usuarios_rol    FOREIGN KEY (rol_id)    REFERENCES roles(id)   ON DELETE SET NULL,
  CONSTRAINT fk_usuarios_estado FOREIGN KEY (estado_id) REFERENCES estados(id) ON DELETE SET NULL
);

CREATE TABLE proveedores (
  id          NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre      VARCHAR2(160) NOT NULL,
  contacto    VARCHAR2(120),
  tel         VARCHAR2(40),
  email       VARCHAR2(160),
  usuario_id  NUMBER(10),
  created_at  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_proveedores_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE SET NULL
);

-- ─── SECCIÓN 4: Parcelas y trabajadores ──────────────────────────────────────

CREATE TABLE parcelas (
  id              NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre          VARCHAR2(120) NOT NULL,
