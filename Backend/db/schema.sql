CREATE OR REPLACE VIEW V_DASHBOARD AS
SELECT
  u.id               AS usuario_id,
  u.nombre           AS usuario_nombre,
  r.nombre           AS rol,
  e.nombre           AS estado,
  (SELECT COUNT(*) FROM parcelas p
     JOIN estados ep ON ep.id = p.estado_id AND ep.nombre = 'Activa'
   WHERE p.usuario_id = u.id)                                       AS parcelas_activas,
  (SELECT COUNT(*) FROM trabajadores t
     JOIN estados et ON et.id = t.estado_id AND et.nombre = 'Activo'
   WHERE t.usuario_id = u.id)                                       AS trabajadores_activos,
  (SELECT NVL(SUM(monto), 0) FROM ingresos
   WHERE usuario_id = u.id
     AND TRUNC(fecha, 'MM') = TRUNC(SYSDATE, 'MM'))                 AS ingresos_mes,
  (SELECT NVL(SUM(monto), 0) FROM egresos
   WHERE usuario_id = u.id
     AND TRUNC(fecha, 'MM') = TRUNC(SYSDATE, 'MM'))                 AS egresos_mes,
  (SELECT COUNT(*) FROM maquinaria WHERE usuario_id = u.id)         AS total_maquinaria,
  (SELECT COUNT(*) FROM campanas
   WHERE usuario_id = u.id
     AND SYSDATE BETWEEN fecha_inicio AND fecha_fin)                 AS campanas_activas,
  (SELECT COUNT(*) FROM siembras s
     JOIN estados es ON es.id = s.estado_id AND es.nombre = 'Activa'
   WHERE s.usuario_id = u.id)                                       AS siembras_activas
FROM usuarios u
LEFT JOIN roles   r ON r.id = u.rol_id
LEFT JOIN estados e ON e.id = u.estado_id;

CREATE OR REPLACE VIEW V_RESUMEN_FINANCIERO AS
SELECT usuario_id, TRUNC(fecha, 'MM') AS mes, 'Ingreso' AS tipo, SUM(monto) AS total
  FROM ingresos GROUP BY usuario_id, TRUNC(fecha, 'MM')
UNION ALL
SELECT usuario_id, TRUNC(fecha, 'MM') AS mes, 'Egreso'  AS tipo, SUM(monto) AS total
  FROM egresos  GROUP BY usuario_id, TRUNC(fecha, 'MM');

CREATE OR REPLACE VIEW V_STOCK_BAJO AS
SELECT
  f.id,
  f.nombre,
  f.stock_kg,
  f.stock_minimo,
  f.stock_kg - f.stock_minimo AS diferencia_kg,
  f.usuario_id
FROM fertilizantes f
WHERE f.stock_minimo > 0
  AND f.stock_kg <= f.stock_minimo;

CREATE OR REPLACE VIEW V_CAMPANAS_RESUMEN AS
SELECT
  c.id          AS campana_id,
  c.nombre,
  c.fecha_inicio,
  c.fecha_fin,
  c.hectareas,
  c.lotes,
  c.usuario_id,
  NVL((SELECT SUM(monto)             FROM ingresos       WHERE campana_id = c.id), 0) AS ingreso_total,
  NVL((SELECT SUM(monto)             FROM egresos        WHERE campana_id = c.id), 0) AS egresos_total,
  NVL((SELECT SUM(bultos)            FROM campanas_diario WHERE campana_id = c.id), 0) AS produccion_total,
  NVL((SELECT SUM(hectareas_cortadas) FROM campanas_diario WHERE campana_id = c.id), 0) AS hectareas_cosechadas,
  CASE
    WHEN NVL((SELECT SUM(hectareas_cortadas) FROM campanas_diario WHERE campana_id = c.id), 0) > 0
    THEN ROUND(
           NVL((SELECT SUM(bultos) FROM campanas_diario WHERE campana_id = c.id), 0) /
           (SELECT SUM(hectareas_cortadas) FROM campanas_diario WHERE campana_id = c.id), 2)
    ELSE 0
  END AS rendimiento_ha
FROM campanas c;

-- Total de horas por trabajador (útil para nómina y reportes)
CREATE OR REPLACE VIEW V_TRABAJADORES_HORAS AS
SELECT
  t.id          AS trabajador_id,
  t.nombre      AS trabajador_nombre,
  c.nombre      AS cargo,
  e.nombre      AS estado,
  t.salario,
  t.usuario_id,
  NVL(SUM(h.horas), 0)                                           AS horas_totales,
  NVL(SUM(CASE WHEN TRUNC(h.fecha,'MM') = TRUNC(SYSDATE,'MM')
               THEN h.horas END), 0)                             AS horas_mes_actual,
  COUNT(DISTINCT h.fecha)                                        AS dias_trabajados
FROM trabajadores t
LEFT JOIN cargos        c ON c.id = t.cargo_id
LEFT JOIN estados       e ON e.id = t.estado_id
LEFT JOIN horas_laboradas h ON h.trabajador_id = t.id
GROUP BY t.id, t.nombre, c.nombre, e.nombre, t.salario, t.usuario_id;

-- Siembras con resumen de inversión y uso de fertilizantes
CREATE OR REPLACE VIEW V_SIEMBRAS_RESUMEN AS
SELECT
  s.id              AS siembra_id,
  s.fecha_siembra,
  s.cantidad_kg,
  p.nombre          AS parcela,
  ts.nombre         AS tipo_semilla,
  pr.nombre         AS proveedor,
  e.nombre          AS estado,
  s.usuario_id,
  NVL((SELECT SUM(monto) FROM inversiones     WHERE siembra_id = s.id), 0) AS inversion_total,
