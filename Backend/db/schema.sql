  CONSTRAINT fk_parcelas_estado  FOREIGN KEY (estado_id)       REFERENCES estados(id)       ON DELETE SET NULL,
  CONSTRAINT fk_parcelas_usuario FOREIGN KEY (usuario_id)      REFERENCES usuarios(id)      ON DELETE SET NULL
);

CREATE TABLE trabajadores (
  id          NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre      VARCHAR2(120) NOT NULL,
  cargo_id    NUMBER(10),
  salario     NUMBER(12,2)  DEFAULT 0 NOT NULL,
  estado_id   NUMBER(10),
  usuario_id  NUMBER(10),
  created_at  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at  TIMESTAMP,
  CONSTRAINT fk_trabajadores_cargo   FOREIGN KEY (cargo_id)   REFERENCES cargos(id)   ON DELETE SET NULL,
  CONSTRAINT fk_trabajadores_estado  FOREIGN KEY (estado_id)  REFERENCES estados(id)  ON DELETE SET NULL,
  CONSTRAINT fk_trabajadores_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE SET NULL
);

-- Reemplaza trabajadores.horas_trabajadas (campo acumulado sin historial)
