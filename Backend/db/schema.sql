-- Descuenta stock al registrar uso; lanza error si es insuficiente
CREATE OR REPLACE TRIGGER trg_descontar_stock_fertilizante
BEFORE INSERT ON usos_fertilizante
FOR EACH ROW
DECLARE
  v_stock  NUMBER(10,2);
  v_nombre VARCHAR2(160);
BEGIN
  SELECT stock_kg, nombre INTO v_stock, v_nombre
    FROM fertilizantes WHERE id = :NEW.fertilizante_id;

  IF v_stock < :NEW.cantidad_kg THEN
    RAISE_APPLICATION_ERROR(-20001,
      'Stock insuficiente para "' || v_nombre || '". ' ||
      'Disponible: ' || v_stock || ' kg, requerido: ' || :NEW.cantidad_kg || ' kg.');
  END IF;

  UPDATE fertilizantes
     SET stock_kg = stock_kg - :NEW.cantidad_kg
   WHERE id = :NEW.fertilizante_id;
END;
/

-- Sincroniza estado Disponible/Agotado automáticamente al cambiar stock
CREATE OR REPLACE TRIGGER trg_estado_fertilizante
BEFORE UPDATE OF stock_kg ON fertilizantes
FOR EACH ROW
BEGIN
  IF :NEW.stock_kg <= 0 THEN
    :NEW.estado := 'Agotado';
  ELSIF :NEW.stock_kg > 0 AND :OLD.estado = 'Agotado' THEN
    :NEW.estado := 'Disponible';
  END IF;
END;
/

